const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const express = require('express');
const { once } = require('node:events');
const { WebSocket } = require('ws');
const net = require('node:net');

const root = fs.realpathSync.native(fs.mkdtempSync(path.join(os.tmpdir(), 'pivane-desktop-stop-gateway-')));
process.env.PI_CODING_AGENT_DIR = path.join(root, 'agent');
process.env.PI_PROJECT_ROOTS = root;
process.env.PI_WEB_TOKEN = 'synthetic-desktop-stop-token';
process.env.PI_OFFLINE = '1';
const { createPiAgentGateway } = require('../server/pi-agent-routes');
const { MaintenanceClient } = require('../server/pi-maintenance-client');

test('assembled stop projection covers conservative side chat and private confirmation gates HTTP and WebSocket', async t => {
    const maintenance = new MaintenanceClient({ managed: true, nonce: 'synthetic' });
    maintenance.receive({ type: 'maintenance-activate', nonce: 'synthetic' });
    const mediaLabService = { pendingReviews: 0, stopReadiness() { return this.pendingReviews; } };
    const gateway = createPiAgentGateway({ maintenance, mediaLabService });
    const app = express(); app.use(express.json());
    app.use((req, res, next) => maintenance.http(req, res, next));
    gateway.mount(app);
    const server = app.listen(0, '127.0.0.1'), wss = gateway.attachWebSocket(server);
    await once(server, 'listening');
    t.after(async () => {
        for (const socket of wss.clients) socket.terminate();
        await gateway.dispose(); await new Promise(resolve => server.close(resolve));
        fs.rmSync(root, { recursive: true, force: true });
    });
    await gateway.cron.ready; await gateway.learning.resumePromise;
    const before = gateway.desktopStop.snapshot();
    assert.equal(before.complete, true, JSON.stringify(before));
    assert.deepEqual(before.blockers, []);
    mediaLabService.pendingReviews = 1;
    assert.equal(gateway.desktopStop.review({ action: 'stop' }).ticket, undefined, 'pending media confirmation blocks stopping');
    mediaLabService.pendingReviews = 0;
    gateway.sideChat.connections.add({ dispose: async () => {} });
    const busy = gateway.desktopStop.review({ action: 'stop' });
    assert.equal(busy.ticket, undefined);
    assert.equal(busy.blockers.find(row => row.type === 'side-chat').count, 1);
    gateway.sideChat.connections.clear();
    const socket = new WebSocket(`ws://127.0.0.1:${server.address().port}/api/pi/ws`);
    await once(socket, 'open');
    const first = gateway.desktopStop.review({ action: 'stop' });
    const url = `http://127.0.0.1:${server.address().port}/api/pi/projects/pin`;
    const response = await fetch(url, { method: 'PATCH', headers: { Authorization: 'Bearer synthetic-desktop-stop-token', 'Content-Type': 'application/json' }, body: JSON.stringify({ cwd: root, pinned: true }) });
    assert.equal(response.status, 200);
    assert.throws(() => gateway.desktopStop.execute({ ticket: first.ticket, draftsSaved: true, externalWritersStopped: true }), { code: 'DESKTOP_REVIEW_STALE' });
    const next = gateway.desktopStop.review({ action: 'stop' });
    assert.ok(next.ticket, JSON.stringify(next));
    gateway.desktopStop.execute({ ticket: next.ticket, draftsSaved: true, externalWritersStopped: true });
    assert.equal((await fetch(url, { method: 'PATCH' })).status, 503);
    const message = once(socket, 'message');
    socket.send(JSON.stringify({ type: 'authenticate', id: 'late', token: 'synthetic-desktop-stop-token' }));
    const rejected = JSON.parse((await message)[0]);
    assert.equal(rejected.success, false);
    assert.match(rejected.error, /维护/);
    await assert.rejects(gateway.supervisor.createEphemeralWorker(root), /维护/);
    assert.equal(gateway.supervisor.workers.size, 0);
    const stalled = net.createConnection(server.address().port, '127.0.0.1');
    await once(stalled, 'connect');
    const upgraded = once(stalled, 'data');
    stalled.write(`GET /api/pi/ws HTTP/1.1\r\nHost: 127.0.0.1:${server.address().port}\r\nUpgrade: websocket\r\nConnection: Upgrade\r\nSec-WebSocket-Key: dGhlIHNhbXBsZSBub25jZQ==\r\nSec-WebSocket-Version: 13\r\n\r\n`);
    assert.match((await upgraded)[0].toString(), /101 Switching Protocols/);
    const closed = once(socket, 'close'), stalledClosed = once(stalled, 'close');
    const began = Date.now(), disposal = gateway.dispose();
    assert.equal(gateway.dispose(), disposal, 'repeated disposal shares the same transport and worker cleanup');
    await disposal;
    assert.equal((await closed)[0], 1001, 'cooperating workbenches receive a normal service close');
    await stalledClosed;
    assert.ok(Date.now() - began < 6000, 'a peer ignoring the close handshake cannot hold the HTTP drain');
});
